defmodule Mix.Tasks.Pidro.Selfplay do
  @moduledoc """
  Plays seeded games between two bot teams and prints how each team did.

      mix pidro.selfplay                          # 2000 games, seed 1, rulebook vs random
      mix pidro.selfplay --games 500 --seed 7
      mix pidro.selfplay --a rulebook --b rulebook
      mix pidro.selfplay --pairs 1000 --seed 71 --a rulebook --b random
      mix pidro.selfplay --pairs 1000 --seed 3790 --a search --b rulebook --worlds 100 --veto 0.4

  `search` is the research search bot (`Pidro.Bot.Search`), never a table's
  bot; `--worlds` (default 100) and `--veto` (default 0.4) set its budget and
  readability veto. `--report FILE` writes the 20 most frequent positions
  where search overruled the rulebook to FILE as Markdown.

  Team A alternates between North/South and East/West. The summary reports
  win rate, bids made and set, points lost to sets, average winning bid,
  decision times, and any illegal move, crash, stall or capped game. The task
  exits non-zero if a game did not finish cleanly. Needs no database.
  """
  use Mix.Task

  alias Pidro.Bot.{Search, SelfPlay}

  @shortdoc "Plays seeded bot-vs-bot games and prints a summary"

  @policies ~w(rulebook random regular search)

  @impl Mix.Task
  def run(args) do
    {opts, rest, invalid} =
      OptionParser.parse(args,
        strict: [
          games: :integer,
          pairs: :integer,
          seed: :integer,
          a: :string,
          b: :string,
          worlds: :integer,
          veto: :float,
          report: :string
        ]
      )

    if invalid != [], do: usage("Unknown options: #{inspect(invalid)}")
    if rest != [], do: usage("Unexpected arguments: #{inspect(rest)}")

    if Keyword.has_key?(opts, :pairs) and Keyword.has_key?(opts, :games),
      do: usage("Choose --pairs or --games, not both")

    count_key = if Keyword.has_key?(opts, :pairs), do: :pairs, else: :games
    count = Keyword.get(opts, count_key, 2000)
    if count < 1, do: usage("Game/pair count must be positive")

    a = Keyword.get(opts, :a, "rulebook")
    b = Keyword.get(opts, :b, "random")
    {:ok, critic} = Agent.start_link(fn -> [] end)

    search = [
      worlds: Keyword.get(opts, :worlds, 100),
      veto: Keyword.get(opts, :veto, 0.4),
      seed: Keyword.get(opts, :seed, 1),
      critic: critic
    ]

    policy_a = policy(a, search)
    policy_b = policy(b, search)
    {label_a, label_b} = if a == b, do: {"#{a}_a", "#{b}_b"}, else: {a, b}

    summary =
      SelfPlay.run(
        [{count_key, count}] ++
          [
            seed: Keyword.get(opts, :seed, 1),
            a: {String.to_atom(label_a), policy_a},
            b: {String.to_atom(label_b), policy_b}
          ]
      )

    Mix.shell().info(SelfPlay.format(summary))

    if path = opts[:report] do
      records = Agent.get(critic, & &1)

      header = """
      # Where search overrules the rulebook

      The #{min(length(records), 20)} most frequent position shapes where `Pidro.Bot.Search`
      chose another move than `Pidro.Bot.Rulebook`, out of #{length(records)} overruled
      decisions, with one example each. Generated by
      `mix pidro.selfplay #{Enum.join(args, " ")}`.

      """

      File.write!(path, header <> Search.report(records))
      Mix.shell().info("Wrote the search disagreements to #{path}")
    end

    if summary.complete != summary.games do
      Mix.shell().error("Games that did not finish: #{inspect(summary.failures)}")
      exit({:shutdown, 1})
    end
  end

  defp policy("rulebook", _search), do: SelfPlay.rulebook_policy()
  defp policy("random", _search), do: SelfPlay.random_policy()
  defp policy("regular", _search), do: SelfPlay.rulebook_policy()
  defp policy("search", search), do: SelfPlay.search_policy(search)

  defp policy(name, _search),
    do: usage("Unknown policy #{inspect(name)}; use one of #{Enum.join(@policies, ", ")}")

  defp usage(message) do
    Mix.shell().error(message)

    Mix.shell().info(
      "Usage: mix pidro.selfplay [--games N | --pairs N] [--seed N] [--a POLICY] [--b POLICY] [--worlds K] [--veto M] [--report FILE]\nPolicies: #{Enum.join(@policies, ", ")}"
    )

    exit({:shutdown, 1})
  end
end
