defmodule PidroServerWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :pidro_server

  # Admin browser sessions are encrypted, HTTP-only, and expire after 14 days.
  # Player authentication uses independent bearer tokens and never touches this cookie.
  @session_options [
    store: :cookie,
    key: "_pidro_admin_key",
    signing_salt: "OHF91k4t",
    encryption_salt: "5GC9r2Bq",
    same_site: "Lax",
    http_only: true,
    secure: Application.compile_env(:pidro_server, :admin_cookie_secure, false),
    max_age: 14 * 24 * 60 * 60
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # WebSocket for game channels
  socket "/socket", PidroServerWeb.UserSocket,
    auth_token: true,
    websocket: [log: false],
    longpoll: [log: false]

  # Restore the client address and scheme from kamal-proxy's X-Forwarded-*
  # headers for the HTTP pipeline. A no-op unless :trust_proxy_headers is
  # true and the TCP peer is proxy-side. WebSocket upgrades never reach this
  # plug: `use Phoenix.Endpoint` injects `plug :socket_dispatch` ahead of every
  # user plug and it halts on a socket path, so socket connect_info still sees
  # the proxy address.
  plug PidroServerWeb.Plugs.TrustedProxy

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :pidro_server,
    gzip: not code_reloading?,
    only: PidroServerWeb.static_paths()

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :pidro_server
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint], log: {__MODULE__, :log_level, []}

  # Before report auth/body admission so browser clients can read 401/413/429.
  plug CORSPlug,
    origin: &PidroServerWeb.Endpoint.cors_origins/0,
    headers: ["Authorization", "Content-Type", "Accept"],
    methods: ["GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"],
    expose: ["retry-after"]

  plug PidroServerWeb.Plugs.GameReportBodyLimit

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    length: 5_308_416,
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options

  plug PidroServerWeb.Router

  @doc """
  Request log level for `Plug.Telemetry`: a request that went well is debug
  chatter, a 4xx or 5xx stays in the logs. The request start has no status yet.
  """
  def log_level(%Plug.Conn{status: status}) when is_integer(status) and status >= 400, do: :info
  def log_level(%Plug.Conn{}), do: :debug

  @doc """
  Returns the list of allowed CORS origins based on environment configuration.

  In development: allows all origins (*)
  In production: uses the CORS_ORIGINS environment variable (comma-separated list)
  """
  def cors_origins do
    case Application.get_env(:pidro_server, :cors_origins) do
      :all -> ["*"]
      origins when is_list(origins) -> origins
      _ -> ["*"]
    end
  end
end
